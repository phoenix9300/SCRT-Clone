module.exports = async ({ page, shot }) => {
  const assert = (c, m) => { if (!c) throw new Error('ASSERT ' + m); };
  const F = (l) => page.locator(`.dialog .field:has(> label:text-is("${l}"))`);
  const nav = (t) => page.locator(`.dialog nav .nav-item:text-is("${t}")`).click();
  const openMenu = async (m, item) => { await page.locator('.menu-title', { hasText: m }).first().click(); await page.locator('.popup .item', { hasText: item }).first().click(); };
  // --- new session
  await openMenu('File', 'New Session');
  await page.waitForSelector('.dialog[aria-label="New Session"]');
  await F('Name').locator('input').fill('lab/router1'.replace('lab/', ''));
  await F('Host').locator('input').fill('10.1.2.3');
  await F('Username').locator('input').fill('admin');
  await F('Description').locator('input').fill('core router');
  await F('Port').locator('input').fill('2222');
  await nav('SSH2'); await F('Keep-alive (seconds)').locator('input').fill('15');
  await page.locator('.dialog label.check', { hasText: 'Forward agent' }).locator('input').check();
  await nav('Emulation'); await F('Scrollback (lines)').locator('input').fill('7777');
  await F('Emulation').locator('select').selectOption('vt220');
  await nav('Appearance'); await page.locator('.dialog .opt-box label', { hasText: 'Dracula' }).first().locator('input').check().catch(() => {});
  await F('Font size').locator('input').fill('16');
  await nav('Mapped Keys'); await page.click('.dialog >> text=Add mapped key');
  await page.keyboard.press('Control+F5');
  await page.locator('.dialog .opt-list input.input').first().fill('ls\\r');
  await nav('Logon Actions'); await page.click('.dialog >> text=Add action');
  await page.locator('.dialog input[placeholder^="Expect"]').fill('login:');
  await nav('Port Forwarding'); await page.click('.dialog >> text=Add forward');
  await page.locator('.dialog[aria-label="Port Forward"] .field:has(> label:text-is("Name")) input').fill('web');
  await page.locator('.dialog[aria-label="Port Forward"] .field:has(> label:text-is("Bind port")) input').fill('8080');
  await page.locator('.dialog[aria-label="Port Forward"] .field:has(> label:text-is("Destination host")) input').fill('intranet');
  await page.locator('.dialog[aria-label="Port Forward"] .field:has(> label:text-is("Destination port")) input').fill('80');
  await page.locator('.dialog[aria-label="Port Forward"] button.primary').click();
  await nav('Connection'); await F('Password').locator('input').fill('s3cret');
  await shot('opt-new');
  await page.click('.dialog button.primary');
  await page.waitForSelector('.dialog', { state: 'detached' });
  // --- reopen via session tree
  await page.locator('.tree-row', { hasText: 'router1' }).click({ button: 'right' });
  await page.locator('.popup .item', { hasText: /Properties|Options|Edit/ }).first().click();
  await page.waitForSelector('.dialog[aria-label^="Session Options"]');
  const v = async (l) => F(l).locator('input,select').first().inputValue();
  assert(await v('Name') === 'router1', 'name');
  assert(await v('Host') === '10.1.2.3', 'host');
  assert(await v('Port') === '2222', 'port');
  assert(await v('Username') === 'admin', 'user');
  assert((await F('Password').locator('input').getAttribute('placeholder')).includes('saved'), 'pw saved');
  await nav('SSH2'); assert(await v('Keep-alive (seconds)') === '15', 'keepalive');
  assert(await page.locator('.dialog label.check', { hasText: 'Forward agent' }).locator('input').isChecked(), 'agentfwd');
  await nav('Emulation'); assert(await v('Scrollback (lines)') === '7777', 'scrollback'); assert(await v('Emulation') === 'vt220', 'emul');
  await nav('Appearance'); assert(await v('Font size') === '16', 'fontsize');
  await nav('Mapped Keys'); assert((await page.locator('.dialog .opt-list button').first().innerText()).includes('Ctrl+F5'), 'mapped key');
  await nav('Logon Actions'); assert(await page.locator('.dialog input[placeholder^="Expect"]').inputValue() === 'login:', 'logon');
  await nav('Port Forwarding'); assert((await page.locator('.dialog table.grid').innerText()).includes('intranet:80'), 'forward');
  // rename + save
  await nav('Connection'); await F('Name').locator('input').fill('router2');
  await page.click('.dialog button.primary');
  await page.waitForSelector('.dialog', { state: 'detached' });
  await page.locator('.tree-row', { hasText: 'router2' }).waitFor();
  // --- default session
  await openMenu('Options', 'Default Session');
  await page.waitForSelector('.dialog[aria-label="Default Session Options"]');
  assert(await F('Name').count() === 0, 'default hides name');
  await nav('Emulation'); await F('Scrollback (lines)').locator('input').fill('1234');
  await page.click('.dialog button.primary'); await page.waitForSelector('.dialog', { state: 'detached' });
  await openMenu('Options', 'Default Session');
  await nav('Emulation'); assert(await v('Scrollback (lines)') === '1234', 'default persisted');
  await page.keyboard.press('Escape');
  // --- global options + editors
  await openMenu('Options', 'Global Options');
  await page.waitForSelector('.dialog[aria-label="Global Options"]');
  await F('Theme').locator('select').selectOption('light');
  await F('Python path').locator('input').fill('/usr/bin/python3');
  await page.click('.dialog button:text-is("Edit schemes…")');
  await page.waitForSelector('.dialog[aria-label="Colour Schemes"]');
  await page.click('.dialog[aria-label="Colour Schemes"] >> text=Add');
  await page.locator('.dialog[aria-label="Colour Schemes"] .field input').fill('Mine');
  await page.locator('.dialog[aria-label="Colour Schemes"] input[type=color]').first().evaluate((e) => { e.value = '#112233'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await shot('opt-schemes');
  await page.click('.dialog[aria-label="Colour Schemes"] button.primary');
  await page.click('.dialog[aria-label="Global Options"] button.primary');
  await page.waitForSelector('.dialog', { state: 'detached' });
  assert(await page.evaluate(() => document.documentElement.dataset.theme) === 'light', 'theme light');
  // keywords
  await openMenu('Options', 'Keyword');
  await page.waitForSelector('.dialog[aria-label="Keyword Highlighting"]');
  await page.click('.dialog >> text=Add rule');
  await page.locator('.dialog input[placeholder="text or regex"]').last().fill('PANIC');
  await page.click('.dialog button.primary'); await page.waitForSelector('.dialog', { state: 'detached' });
  await openMenu('Options', 'Keyword');
  assert(await page.locator('.dialog input[value="PANIC"]').count() === 1, 'keyword persisted');
  await page.keyboard.press('Escape');
  // button bar
  await openMenu('Options', 'Button Bar');
  await page.waitForSelector('.dialog[aria-label="Button Bar"]');
  await page.click('.dialog >> text=Add button');
  await page.locator('.dialog input[placeholder="Label"]').fill('Hello');
  await page.locator('.dialog input[placeholder^="text"]').fill('echo hi\\r');
  await page.click('.dialog button.primary'); await page.waitForSelector('.dialog', { state: 'detached' });
  await openMenu('Options', 'Button Bar');
  assert(await page.locator('.dialog input[value="Hello"]').count() === 1, 'button persisted');
  await page.keyboard.press('Escape');
  // shortcuts
  await openMenu('Options', 'Keyboard Shortcuts');
  await page.waitForSelector('.dialog[aria-label="Keyboard Shortcuts"]');
  const row = page.locator('.dialog tr', { has: page.locator('td:text-is("find")') });
  await row.locator('button:text-is("Set")').click();
  await page.keyboard.press('Control+Alt+J');
  assert((await row.innerText()).includes('Ctrl+Alt+J'), 'shortcut set');
  await shot('opt-shortcuts');
  await page.click('.dialog button.primary'); await page.waitForSelector('.dialog', { state: 'detached' });
  assert(await page.evaluate(() => 1), 'done');
};
