package vbs

import "testing"

func TestDateBuiltins(t *testing.T) {
	evalCases(t, []ecase{
		{`DateSerial(2020, 3, 4)`, "3/4/2020"},
		{`DateSerial(2020, 14, 1)`, "2/1/2021"},
		{`DateSerial(2020, 3, 0)`, "2/29/2020"},
		{`DateSerial(2020, 1, 32)`, "2/1/2020"},
		{`DateSerial(2020, 0, 1)`, "12/1/2019"},
		{`DateSerial(99, 1, 1)`, "1/1/1999"},
		{`DateSerial(29, 1, 1)`, "1/1/2029"},
		{`DateSerial(30, 1, 1)`, "1/1/1930"},
		{`TimeSerial(13, 5, 9)`, "1:05:09 PM"},
		{`TimeSerial(0, 0, 0)`, "12:00:00 AM"},
		{`Hour(TimeSerial(25, 0, 0))`, "1"},
		{`Minute(TimeSerial(1, 90, 0))`, "30"},
		{`DateValue("2020-03-04 10:00")`, "3/4/2020"},
		{`TimeValue("2020-03-04 10:11:12")`, "10:11:12 AM"},
		{`DateAdd("d", 1, DateSerial(2020, 2, 28))`, "2/29/2020"},
		{`DateAdd("d", 2, DateSerial(2020, 2, 28))`, "3/1/2020"},
		{`DateAdd("m", 1, DateSerial(2020, 1, 31))`, "2/29/2020"},
		{`DateAdd("m", -1, DateSerial(2020, 3, 31))`, "2/29/2020"},
		{`DateAdd("yyyy", 1, DateSerial(2020, 2, 29))`, "2/28/2021"},
		{`DateAdd("q", 1, DateSerial(2020, 1, 15))`, "4/15/2020"},
		{`DateAdd("ww", 1, DateSerial(2020, 1, 1))`, "1/8/2020"},
		{`DateAdd("h", 5, DateSerial(2020, 1, 1))`, "1/1/2020 5:00:00 AM"},
		{`DateAdd("n", 90, DateSerial(2020, 1, 1))`, "1/1/2020 1:30:00 AM"},
		{`DateAdd("s", 61, DateSerial(2020, 1, 1))`, "1/1/2020 12:01:01 AM"},
		{`DateAdd("y", 1, DateSerial(2020, 12, 31))`, "1/1/2021"},
		{`DateAdd("w", 1, DateSerial(2020, 12, 31))`, "1/1/2021"},
		{`DateDiff("d", DateSerial(2020, 1, 1), DateSerial(2020, 3, 1))`, "60"},
		{`DateDiff("d", DateSerial(2020, 3, 1), DateSerial(2020, 1, 1))`, "-60"},
		{`DateDiff("m", DateSerial(2020, 1, 31), DateSerial(2020, 2, 1))`, "1"},
		{`DateDiff("yyyy", DateSerial(2019, 12, 31), DateSerial(2020, 1, 1))`, "1"},
		{`DateDiff("q", DateSerial(2020, 1, 1), DateSerial(2020, 12, 31))`, "3"},
		{`DateDiff("h", DateSerial(2020, 1, 1), DateSerial(2020, 1, 2))`, "24"},
		{`DateDiff("n", DateSerial(2020, 1, 1), DateSerial(2020, 1, 2))`, "1440"},
		{`DateDiff("s", DateSerial(2020, 1, 1), DateSerial(2020, 1, 2))`, "86400"},
		{`DateDiff("ww", DateSerial(2020, 1, 1), DateSerial(2020, 1, 15))`, "2"},
		{`DateDiff("w", DateSerial(2020, 1, 1), DateSerial(2020, 1, 15))`, "2"},
		{`DateDiff("d", DateSerial(2020, 1, 1), DateSerial(2020, 1, 1))`, "0"},
		{`DatePart("yyyy", DateSerial(2020, 3, 4))`, "2020"},
		{`DatePart("m", DateSerial(2020, 3, 4))`, "3"},
		{`DatePart("d", DateSerial(2020, 3, 4))`, "4"},
		{`DatePart("q", DateSerial(2020, 5, 4))`, "2"},
		{`DatePart("y", DateSerial(2020, 3, 1))`, "61"},
		{`DatePart("w", DateSerial(2020, 3, 4))`, "4"},
		{`DatePart("h", #2020-03-04 13:05:09#)`, "13"},
		{`DatePart("n", #2020-03-04 13:05:09#)`, "5"},
		{`DatePart("s", #2020-03-04 13:05:09#)`, "9"},
		{`DatePart("ww", DateSerial(2020, 1, 1))`, "1"},
		{`DatePart("ww", DateSerial(2020, 1, 8))`, "2"},
		{`Year(DateSerial(2020, 3, 4))`, "2020"},
		{`Month(DateSerial(2020, 3, 4))`, "3"},
		{`Day(DateSerial(2020, 3, 4))`, "4"},
		{`Weekday(DateSerial(2020, 3, 4))`, "4"},
		{`Weekday(DateSerial(2020, 3, 1))`, "1"},
		{`Weekday(DateSerial(2020, 3, 7))`, "7"},
		{`Weekday(DateSerial(2020, 3, 4), vbMonday)`, "3"},
		{`Weekday(DateSerial(2020, 3, 1), vbMonday)`, "7"},
		{`WeekdayName(1)`, "Sunday"},
		{`WeekdayName(7)`, "Saturday"},
		{`WeekdayName(1, True)`, "Sun"},
		{`WeekdayName(1, False, vbMonday)`, "Monday"},
		{`WeekdayName(2, False, vbMonday)`, "Tuesday"},
		{`MonthName(1)`, "January"},
		{`MonthName(12)`, "December"},
		{`MonthName(3, True)`, "Mar"},
		{`FormatDateTime(DateSerial(2020, 3, 4), vbShortDate)`, "3/4/2020"},
		{`FormatDateTime(DateSerial(2020, 3, 4), vbLongDate)`, "Wednesday, March 4, 2020"},
		{`FormatDateTime(DateSerial(2020, 3, 4))`, "3/4/2020"},
		{`FormatDateTime(#2020-03-04 13:05:09#, vbLongTime)`, "1:05:09 PM"},
		{`FormatDateTime(#2020-03-04 13:05:09#, vbShortTime)`, "13:05"},
		{`FormatDateTime(#2020-03-04 13:05:09#, vbGeneralDate)`, "3/4/2020 1:05:09 PM"},
		{`FormatDateTime(#2020-03-04 13:05:09#)`, "3/4/2020 1:05:09 PM"},
		{`CDbl(DateSerial(2020, 3, 4))`, "43894"},
		{`CDbl(TimeSerial(12, 0, 0))`, "0.5"},
		{`DateSerial(2020, 3, 4) + 1`, "3/5/2020"},
		{`DateSerial(2020, 3, 4) - DateSerial(2020, 3, 1)`, "3"},
		{`DateSerial(2020, 3, 4) < DateSerial(2020, 3, 5)`, "True"},
		{`DateSerial(2020, 3, 4) = #3/4/2020#`, "True"},
		{`CDate(43894)`, "3/4/2020"},
		{`CDate(43894.5)`, "3/4/2020 12:00:00 PM"},
		{`Year(Now) >= 2024`, "True"},
		{`Date = DateValue(Now)`, "True"},
		{`Timer >= 0`, "True"},
		{`TypeName(Now)`, "Date"},
		{`TypeName(Time)`, "Date"},
	})
	runErrCases(t, []errCase{
		{"bad interval", "x = DateAdd(\"zz\", 1, Now)", 5, 1, false},
		{"bad month", "x = MonthName(13)", 5, 1, false},
		{"bad weekday", "x = WeekdayName(8)", 5, 1, false},
		{"year range", "x = DateSerial(10000, 1, 1)", 5, 1, false},
		{"year of text", "x = Year(\"nope\")", 13, 1, false},
	})
}
