func TestConversionBuiltins(t *testing.T) {
	evalCases(t, []ecase{
		{`CStr(12)`, "12"},
		{`CStr(True)`, "True"},
		{`CStr(1.5)`, "1.5"},
		{`CStr(Empty)`, ""},
		{`CInt("12")`, "12"},
		{`CInt(2.5)`, "2"},
		{`CInt(3.5)`, "4"},
		{`CInt(-2.5)`, "-2"},
		{`CInt(-3.5)`, "-4"},
		{`CInt(2.51)`, "3"},
		{`CInt(True)`, "-1"},
		{`CLng(123456.5)`, "123456"},
		{`CLng(123457.5)`, "123458"},
		{`CLng("&H10")`, "16"},
		{`CByte(200)`, "200"},
		{`CDbl("1.5")`, "1.5"},
		{`CDbl(3)`, "3"},
		{`TypeName(CDbl(3))`, "Double"},
		{`TypeName(CInt(3))`, "Integer"},
		{`CBool(0)`, "False"},
		{`CBool(1)`, "True"},
		{`CBool(-5)`, "True"},
		{`CBool("True")`, "True"},
		{`CBool("false")`, "False"},
		{`CBool("1")`, "True"},
		{`CBool(0.0)`, "False"},
		{`CDate("2020-03-04")`, "3/4/2020"},
		{`CDate("3/4/2020 1:02:03")`, "3/4/2020 1:02:03 AM"},
		{`Year(CDate("2020-03-04"))`, "2020"},
		{`CDbl(CDate("1899-12-31"))`, "1"},
		{`CDbl(DateSerial(1900,1,1))`, "2"},
		{`Hex(255)`, "FF"},
		{`Hex(0)`, "0"},
		{`Hex(-1)`, "FFFF"},
		{`Hex(16)`, "10"},
		{`Hex(65536)`, "10000"},
		{`Hex(2.5)`, "2"},
		{`Oct(8)`, "10"},
		{`Oct(64)`, "100"},
		{`Oct(-1)`, "177777"},
		{`Int(2.9)`, "2"},
		{`Int(-2.1)`, "-3"},
		{`Int(5)`, "5"},
		{`Int("3.7")`, "3"},
		{`Fix(2.9)`, "2"},
		{`Fix(-2.9)`, "-2"},
		{`Abs(-3)`, "3"},
		{`Abs(3.5)`, "3.5"},
		{`Abs(-0.5)`, "0.5"},
		{`Abs("-4")`, "4"},
		{`Sgn(-5)`, "-1"},
		{`Sgn(0)`, "0"},
		{`Sgn(0.1)`, "1"},
		{`Round(2.5)`, "2"},
		{`Round(3.5)`, "4"},
		{`Round(-2.5)`, "-2"},
		{`Round(0.5)`, "0"},
		{`Round(1.5)`, "2"},
		{`Round(3.14159, 2)`, "3.14"},
		{`Round(2.675, 2)`, "2.68"},
		{`Round(1.005, 2)`, "1"},
		{`Round(1.015, 2)`, "1.02"},
		{`CStr(1234567890123456)`, "1.23456789012346E+15"},
		{`FormatCurrency(-3, 0)`, "($3)"},
		{`Trim(Chr(9) & "a")`, "	a"},
		{`Round(1.25, 1)`, "1.2"},
		{`Round(1.35, 1)`, "1.4"},
		{`Sqr(16)`, "4"},
		{`Sqr(2)`, "1.4142135623731"},
		{`Exp(0)`, "1"},
		{`Log(1)`, "0"},
		{`Sin(0)`, "0"},
		{`Cos(0)`, "1"},
		{`Atn(1) * 4`, "3.14159265358979"},
		{`Tan(0)`, "0"},
		{`Rnd < 1`, "True"},
		{`CCur(1.2345)`, "1.2345"},
		{`CSng(0.1)`, "0.1"},
		{`CStr(#2020-03-04 13:05:00#)`, "3/4/2020 1:05:00 PM"},
		{`CStr(1E-5)`, "1E-05"},
		{`CStr(123456789.123)`, "123456789.123"},
		{`CStr(0.000123)`, "0.000123"},
		{`CStr(1E15)`, "1E+15"},
		{`CStr(-0.5)`, "-0.5"},
	})
	runErrCases(t, []errCase{
		{"sqr negative", "x = Sqr(-1)", 5, 1, false},
		{"log zero", "x = Log(0)", 5, 1, false},
		{"cdate bad", "x = CDate(\"nope\")", 13, 1, false},
		{"cbool bad", "x = CBool(\"nope\")", 13, 1, false},
		{"abs str", "x = Abs(\"a\")", 13, 1, false},
		{"wrong arg count", "x = Left(\"a\")", 450, 1, false},
	})
}

func TestStringBuiltins(t *testing.T) {
	evalCases(t, []ecase{
		{`Len("hello")`, "5"},
		{`Len("")`, "0"},
		{`Len(12345)`, "5"},
		{`IsNull(Len(Null))`, "True"},
		{`Left("hello", 2)`, "he"},
		{`Left("hello", 10)`, "hello"},
		{`Left("hello", 0)`, ""},
		{`Right("hello", 2)`, "lo"},
		{`Right("hello", 10)`, "hello"},
		{`Mid("hello", 2, 3)`, "ell"},
		{`Mid("hello", 2)`, "ello"},
		{`Mid("hello", 10)`, ""},
		{`Mid("hello", 4, 100)`, "lo"},
		{`Mid("hello", 1, 0)`, ""},
		{`InStr("hello", "l")`, "3"},
		{`InStr("hello", "z")`, "0"},
		{`InStr("hello", "")`, "1"},
		{`InStr(4, "hello", "l")`, "4"},
		{`InStr(5, "hello", "l")`, "0"},
		{`InStr(1, "Hello", "h")`, "0"},
		{`InStr(1, "Hello", "h", 1)`, "1"},
		{`InStr(1, "Hello", "h", vbTextCompare)`, "1"},
		{`InStr(1, "Hello", "h", vbBinaryCompare)`, "0"},
		{`InStr("abcabc", "c")`, "3"},
		{`InStr(2, "abcabc", "")`, "2"},
		{`InStrRev("abcabc", "b")`, "5"},
		{`InStrRev("abcabc", "b", 4)`, "2"},
		{`InStrRev("abcabc", "z")`, "0"},
		{`InStrRev("abcABC", "b", -1, 1)`, "5"},
		{`InStrRev("abcabc", "b", -1, 0)`, "5"},
		{`LCase("HeLLo")`, "hello"},
		{`UCase("HeLLo")`, "HELLO"},
		{`"[" & Trim("  a b  ") & "]"`, "[a b]"},
		{`"[" & LTrim("  a ") & "]"`, "[a ]"},
		{`"[" & RTrim("  a ") & "]"`, "[  a]"},
		{`Replace("a-b-c", "-", "+")`, "a+b+c"},
		{`Replace("a-b-c", "-", "+", 1, 1)`, "a+b-c"},
		{`Replace("a-b-c", "-", "+", 3)`, "b+c"},
		{`Replace("a-b-c", "-", "+", 3, 1)`, "b+c"},
		{`Replace("a-b-c", "-", "+", 1, 0)`, "a-b-c"},
		{`Replace("aAa", "a", "x")`, "xAx"},
		{`Replace("aAa", "a", "x", 1, -1, 1)`, "xxx"},
		{`Replace("aAa", "a", "x", 1, -1, vbTextCompare)`, "xxx"},
		{`Replace("abc", "", "x")`, "abc"},
		{`Replace("abc", "b", "")`, "ac"},
		{`UBound(Split("a,b,c", ","))`, "2"},
		{`Split("a,b,c", ",")(1)`, "b"},
		{`UBound(Split("a,b,c", ",", 2))`, "1"},
		{`Split("a,b,c", ",", 2)(1)`, "b,c"},
		{`UBound(Split("", ","))`, "-1"},
		{`UBound(Split("abc", ","))`, "0"},
		{`Split("a b  c")(2)`, ""},
		{`UBound(Split("a b"))`, "1"},
		{`UBound(Split("aXbxc", "x", -1, 1))`, "2"},
		{`UBound(Split("aXbxc", "x"))`, "1"},
		{`Join(Array("a", "b", "c"), "-")`, "a-b-c"},
		{`Join(Array("a", "b"))`, "a b"},
		{`Join(Array(), ",")`, ""},
		{`Join(Array(1, 2, 3), "")`, "123"},
		{`UBound(Filter(Array("apple", "banana", "cherry"), "an"))`, "0"},
		{`Join(Filter(Array("apple", "banana", "cherry"), "an"), ",")`, "banana"},
		{`Join(Filter(Array("apple", "banana", "cherry"), "an", False), ",")`, "apple,cherry"},
		{`Join(Filter(Array("apple", "Banana"), "AN", True, 1), ",")`, "Banana"},
		{`Join(Filter(Array("apple", "Banana"), "AN"), ",")`, ""},
		{`StrComp("a", "b")`, "-1"},
		{`StrComp("b", "a")`, "1"},
		{`StrComp("a", "a")`, "0"},
		{`StrComp("a", "A")`, "1"},
		{`StrComp("a", "A", 1)`, "0"},
		{`StrComp("a", "A", vbTextCompare)`, "0"},
		{`IsNull(StrComp(Null, "a"))`, "True"},
		{`StrReverse("abc")`, "cba"},
		{`StrReverse("")`, ""},
		{`String(3, "x")`, "xxx"},
		{`String(3, "xyz")`, "xxx"},
		{`String(2, 65)`, "AA"},
		{`String(0, "x")`, ""},
		{`"[" & Space(3) & "]"`, "[   ]"},
		{`Len(Space(0))`, "0"},
		{`Asc("A")`, "65"},
		{`Asc("ABC")`, "65"},
		{`Asc("a")`, "97"},
		{`AscW("A")`, "65"},
		{`Chr(65)`, "A"},
		{`Chr(97) & Chr(98)`, "ab"},
		{`ChrW(65)`, "A"},
		{`Asc(Chr(200))`, "200"},
		{`AscW(ChrW(8364))`, "8364"},
		{`Len(Chr(13) & Chr(10))`, "2"},
		{`FormatNumber(1234.567, 2)`, "1,234.57"},
		{`FormatNumber(1234.567, 0)`, "1,235"},
		{`FormatNumber(0.5, 2)`, "0.50"},
		{`FormatNumber(1234567, 0)`, "1,234,567"},
		{`FormatNumber(-1234.5, 1)`, "-1,234.5"},
		{`FormatNumber(1234.5, 2, , , False)`, "1234.50"},
		{`FormatNumber(0.5, 2, False)`, ".50"},
		{`FormatNumber(0.5, 2, True)`, "0.50"},
		{`FormatNumber(-5, 1, , True)`, "(5.0)"},
		{`FormatNumber(5)`, "5.00"},
		{`FormatPercent(0.256)`, "25.60%"},
		{`FormatPercent(0.256, 0)`, "26%"},
		{`FormatPercent(1, 1)`, "100.0%"},
		{`FormatCurrency(1234.5)`, "$1,234.50"},
		{`LCase(Null & "A")`, "a"},
	})
	runErrCases(t, []errCase{
		{"left negative", "x = Left(\"abc\", -1)", 5, 1, false},
		{"mid zero start", "x = Mid(\"abc\", 0)", 5, 1, false},
		{"chr range", "x = Chr(256)", 5, 1, false},
		{"string neg", "x = String(-1, \"a\")", 5, 1, false},
		{"space neg", "x = Space(-1)", 5, 1, false},
		{"instr start zero", "x = InStr(0, \"a\", \"a\")", 5, 1, false},
		{"join non array", "x = Join(\"a\", \",\")", 13, 1, false},
		{"round negative digits", "x = Round(5, -1)", 5, 1, false},
	})
}

